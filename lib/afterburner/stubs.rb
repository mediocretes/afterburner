# frozen_string_literal: true

require "json"

module Afterburner
  # The JavaScript stubs that stand in for Ruby scripts in the game:
  # src/hello.rb becomes hello.js, which claims the RAM the script needs and
  # hands off to afterburner. Stubs never touch the disk; afterburner pushes
  # them straight to the game, and deletes ones whose script is gone.
  class Stubs
    MARKER = "// Generated by afterburner"
    PROXY = "afterburner/proxy.js"
    CONSOLE = "afterburner/console.js"
    CONSOLE_SCRIPT = "@console"

    Stub = Data.define(:script, :name, :content, :scan)

    def initialize(scripts:, definitions:, costs:, port:, twins: [], log:)
      @scripts = scripts
      @definitions = definitions
      @costs = costs
      @port = port
      @twins = twins # folders where a same-named .js/.ts means skip the stub
      @log = log
      @desired = {}
      @pushed = {}
      @signature = nil
      @warned = Set.new
    end

    def self.proxy_source = File.read(File.expand_path("proxy.js", __dir__))

    # Every stub, keyed by its name in the game. Empty until the game has sent
    # its NetscriptDefinitions.d.ts, which the RAM scan needs.
    def render
      return {} unless File.exist?(@definitions)

      scanner = RamScanner.new(Api.load(@definitions, measured: @costs.load))
      @scripts.entries.filter_map { render_one(_1, scanner) }.to_h { [_1.name, _1] }
    end

    def stub_source(script, ram)
      breakdown = ram.is_a?(RamScanner::Result) ? ram.breakdown : "claimed for the console"
      claim = ram.is_a?(RamScanner::Result) ? ram.ram : ram
      <<~JS
        #{MARKER} from #{script}. Edit that, not this.
        // RAM: #{breakdown}
        import { serve } from "#{PROXY.delete_suffix('.js')}";

        /** @param {NS} ns */
        export async function main(ns) {
          ns.ramOverride(#{claim});
          await serve(ns, #{JSON.generate(script)}, #{@port});
        }
      JS
    end

    def console_source(ram) = stub_source(CONSOLE_SCRIPT, ram)

    # On connect: push the proxy and every stub, and delete stubs left in the
    # game from scripts that are gone.
    def push_all(link)
      link.push_file(PROXY, Stubs.proxy_source)
      @desired = render
      @pushed = {}
      push_changes(link)
      orphans = link.all_files.filter_map do |file|
        name = file["filename"].delete_prefix("/")
        name if file["content"].start_with?(MARKER) && !@desired.key?(name) && name != CONSOLE
      end
      orphans.each do |name|
        link.delete_file(name)
        @log.info("deleted #{name}; its script is gone")
      end
    end

    # Rebuilds when a script, the definitions, or the measured costs change,
    # and pushes the stubs that differ.
    def tick(link)
      signature = current_signature
      if signature != @signature
        @signature = signature
        @desired = render
      end
      push_changes(link) if link
    rescue GameLink::Error => e
      @log.warn(e.message)
    end

    private

    def push_changes(link)
      @desired.each do |name, stub|
        next if @pushed[name] == stub.content

        link.push_file(name, stub.content)
        @log.info("#{stub.script} → #{name} (#{stub.scan.ram} GB)")
        @pushed[name] = stub.content
      end
      (@pushed.keys - @desired.keys).each do |name|
        link.delete_file(name)
        @pushed.delete(name)
        @log.info("deleted #{name}; its script is gone")
      end
    end

    def render_one(script, scanner)
      name = script.sub(/\.rb\z/, ".js")
      twin = @twins.flat_map { |dir| [name, name.sub(/\.js\z/, ".ts")].map { File.join(dir, _1) } }.find { File.exist?(_1) }
      if twin
        warn_once("skipping #{script}: #{twin} would also be #{name} in the game")
        return nil
      end

      scan = scanner.scan(File.join(@scripts.root, script))
      scan.unknown.each { warn_once("#{script}: #{_1} isn't a Netscript function") }
      Stub.new(script:, name:, content: stub_source(script, scan), scan:)
    end

    def current_signature
      files = @scripts.all_files << @definitions
      [files.map { [_1, File.mtime(_1).to_f] if File.exist?(_1) }, @costs.load]
    end

    def warn_once(message)
      @log.warn(message) if @warned.add?(message)
    end
  end
end
